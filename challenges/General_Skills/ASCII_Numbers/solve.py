#!/usr/bin/env python3
"""
Solve script for ASCII Numbers (#390)
Category: General Skills
"""
from pathlib import Path

def solve():
    print("[*] Solving ASCII Numbers...", flush=True)
    raw_hex = (
        "0x61 0x63 0x61 0x64 0x65 0x6d 0x79 0x7b 0x34 0x35 0x63 0x31 0x31 0x5f 0x6e 0x30 0x5f "
        "0x71 0x75 0x33 0x35 0x37 0x31 0x30 0x6e 0x35 0x5f 0x31 0x6c 0x6c 0x5f 0x74 0x33 0x31 "
        "0x31 0x5f 0x79 0x33 0x5f 0x6e 0x30 0x5f 0x6c 0x31 0x33 0x35 0x5f 0x65 0x39 0x36 0x63 "
        "0x38 0x63 0x61 0x38 0x7d"
    )
    tokens = raw_hex.strip().split()
    chars = [chr(int(tok, 16)) for tok in tokens]
    flag = "".join(chars)
    print(f"Decoded flag: {flag}", flush=True)

    # Save to flag.txt
    flag_path = Path(__file__).parent / "flag.txt"
    flag_path.write_text(flag)
    print(f"[+] Flag written to {flag_path}", flush=True)

    return flag

if __name__ == "__main__":
    solve()
